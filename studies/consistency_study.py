"""Filter consistency in the 60-day gap case (Fig. 3 of the article).

For each CMB level and reference sensor of studies/ratio_study.py (group 4), and 6 seeds, computes over the gap:
- the fraction of time the velocity error stays within ±3σ of the filter, per axis;
- the mean velocity NEES (normalized estimation error squared, eᵀP⁻¹e with the full 3×3 velocity covariance,
  expected value 3), and its diagonal approximation Σ e_i²/P_ii;
- the velocity error at the end of the gap.
It also repeats the requirements level with an EKF (analytic Jacobians) and a Gaussian particle filter, to check
that the three filters agree; for the particle filter it records the effective sample size of every update and the
number of fallbacks to the UKF covariance. One seed of normalized per-axis errors is saved for the figure.

Usage (from the repository root): python studies/consistency_study.py [--nproc N]   (~30 min on 2 cores)
Outputs: results/consistency_study.csv, .md and results/consistency_series.npz
"""
from __future__ import annotations

import argparse
import csv
import os
import sys
import time
from multiprocessing import Pool

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.dirname(__file__))
import provenance                                                    # noqa: E402
import gap_study as EL                                               # noqa: E402
import ratio_study as R                                              # noqa: E402
from cmbsim import physics as ph                                     # noqa: E402
from cmbsim.simulator import Config, run                             # noqa: E402

CSV = os.path.join(EL.OUT, "consistency_study.csv")
MD = os.path.join(EL.OUT, "consistency_study.md")
NPZ = os.path.join(EL.OUT, "consistency_series.npz")
SEEDS = R.SEEDS
CASES = {**{k: v for k, v in R.LEVELS.items()}, **R.REFS_GAP}
FILTERS = {"ekf_an": "EKF (analytic Jacobians)", "pf": "Gaussian particle filter"}
FILTER_CASE = "req"
FILTER_SEEDS = (1, 2)
SERIES = ("limit", "xnav")                                            # cases saved for the figure (seed 3)
SERIES_SEED = 3
FIELDS = ["case", "filter", "seed", "ev_end", "within3_x", "within3_y", "within3_z", "nees_mean", "nees_full_mean",
          "pf_ess_median", "pf_ess_p5", "pf_ess_min", "pf_updates", "pf_fallbacks"]


def one(job):
    case, filt, seed = job
    a, b = EL.GAP_START, EL.GAP_START + R.GAP
    kw = {**EL.BASE, **CASES[case][1], "seed": seed, "dsn_gaps": ((a, b),), "end_day": b + 2.0,
          "anomaly_days": (a + 2.0,), "anomaly_dv_mps": EL.ANOM_DV, "filter_type": filt}
    r = run(Config(**kw))
    d = r.t / ph.DAY
    m = (d >= a) & (d <= b)
    e = (r.x_est[m, 3:6] - r.x_true[m, 3:]) * 1e3
    s = np.sqrt(r.P_diag[m, 3:6]) * 1e3
    z = e / s
    row = dict(case=case, filter=filt, seed=seed, ev_end=round(float(np.linalg.norm(e[-1])), 5),
               **{f"within3_{ax}": round(float(np.mean(np.abs(z[:, i]) <= 3) * 100), 1) for i, ax in enumerate("xyz")},
               nees_mean=round(float(np.mean(np.sum(z ** 2, axis=1))), 3))
    Pv = r.info["P_vel"][m] * 1e6                                    # full 3×3 velocity covariance [(m/s)²]
    row["nees_full_mean"] = round(float(np.mean(np.einsum("ti,tij,tj->t", e, np.linalg.inv(Pv), e))), 3)
    pf = r.info.get("pf")
    if pf is not None:                    # effective sample size as a fraction of the particles, per update
        e = pf["ess_frac"]
        row.update(pf_ess_median=round(float(np.median(e)), 6), pf_ess_p5=round(float(np.percentile(e, 5)), 6),
                   pf_ess_min=round(float(e.min()), 4), pf_updates=int(e.size), pf_fallbacks=int(pf["n_fallback"]))
    series = (d[m] - a, z) if (seed == SERIES_SEED and filt == "ukf" and case in SERIES) else None
    return row, series


def rms(x):
    return float(np.sqrt(np.mean(np.square([float(v) for v in x]))))


def summarize(rows):
    L = ["# Filter consistency in the 60-day gap — results", "",
         f"Generated by `studies/consistency_study.py` on {time.strftime('%Y-%m-%d %H:%M')}. 60-day gap at 1.5 AU with "
         f"an anomaly of {EL.ANOM_DV} m/s per axis on day 2; statistics over the gap, {len(SEEDS)} seeds. NEES uses the "
         "full 3×3 velocity covariance; the diagonal approximation is also given (both have expected value 3 for a "
         "consistent filter).", "",
         "| Case | Filter | v error end, RMS [m/s] | Within ±3σ x / y / z [%] | Mean NEES (full) | Mean NEES (diagonal) |",
         "|---|---|---|---|---|---|"]
    keys = [(c, "ukf") for c in CASES] + [(FILTER_CASE, f) for f in FILTERS]
    for c, f in keys:
        s_ = [r for r in rows if r["case"] == c and r["filter"] == f]
        if not s_:
            continue
        w = " / ".join(f"{np.mean([float(r[f'within3_{ax}']) for r in s_]):.0f}" for ax in "xyz")
        fname = "UKF" if f == "ukf" else FILTERS[f]
        L.append(f"| {CASES[c][0]} | {fname} | {rms([r['ev_end'] for r in s_]):.3g} | {w} | "
                 f"{np.mean([float(r['nees_full_mean']) for r in s_]):.2f} | "
                 f"{np.mean([float(r['nees_mean']) for r in s_]):.2f} |")
    pf = [r for r in rows if r["filter"] == "pf" and r.get("pf_ess_median")]
    if pf:
        L += ["", "Gaussian particle filter (shares the UKF prediction; exact measurement model on each particle): "
              "effective sample size as a fraction of the particles.", "",
              "| Seed | Updates | Median | 5th percentile | Minimum | Fallbacks to UKF covariance |",
              "|---|---|---|---|---|---|"]
        for r in sorted(pf, key=lambda r: int(r["seed"])):
            L.append(f"| {r['seed']} | {r['pf_updates']} | {float(r['pf_ess_median']):.6f} | "
                     f"{float(r['pf_ess_p5']):.6f} | {float(r['pf_ess_min']):.3f} | {r['pf_fallbacks']} |")
    with open(MD, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--nproc", type=int, default=os.cpu_count() or 2, help="number of worker processes")
    ap.add_argument("--summary", action="store_true", help="only rebuild the table from the CSV")
    ap.add_argument("--resume-anyway", action="store_true", help="resume even if the CSV was written by other code")
    a = ap.parse_args()
    rows = list(csv.DictReader(open(CSV))) if os.path.exists(CSV) else []
    if a.summary:
        summarize(rows)
        return
    mixed = provenance.check_resume(CSV, a.resume_anyway)
    done = {(r["case"], r["filter"], int(r["seed"])) for r in rows}
    jobs = [(c, "ukf", s) for c in CASES for s in SEEDS] + [(FILTER_CASE, f, s) for f in FILTERS for s in FILTER_SEEDS]
    todo = [j for j in jobs if j not in done or (j[0] in SERIES and j[1] == "ukf" and j[2] == SERIES_SEED)]
    series = dict(np.load(NPZ)) if os.path.exists(NPZ) else {}
    new = not os.path.exists(CSV)
    with open(CSV, "a", newline="") as fh, Pool(a.nproc) as pool:
        w = csv.DictWriter(fh, fieldnames=FIELDS)
        if new:
            w.writeheader()
        for row, ser in pool.imap_unordered(one, todo):
            if (row["case"], row["filter"], row["seed"]) not in done:
                w.writerow(row)
                fh.flush()
                rows.append({k: str(v) for k, v in row.items()})
            if ser is not None:
                series[f"{row['case']}_t"], series[f"{row['case']}_z"] = ser
            print(row, flush=True)
    np.savez(NPZ, **series)
    provenance.stamp(CSV, mixed)
    summarize(rows)


if __name__ == "__main__":
    main()
