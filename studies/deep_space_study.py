"""100 AU mission study (use case 3: interstellar precursor).

Linearised model from `cmbsim/deep.py` (Sun + slow RTG/Pioneer-like non-gravitational acceleration of 1 nm/s² and
fast acceleration of 0.1 nm/s², weekly attitude manoeuvres of 1 mm/s), 1 year starting at 100 AU, leaving at 33 km/s
towards the heliosphere nose. The CMB is the abstract model calibrated against the full simulator ("realistic",
"requirements" and "ideal" levels; see `deep.calibration_case`).

Groups:
1. calibration of the abstract CMB model (60 d gap at 1.5 AU, 12 seeds);
2. DSN alone at 100 AU: weekly, monthly and quarterly passes, with and without ΔDOR (5 nrad);
3. monthly DSN + CMB;
4. autonomous (weekly DSN only during the first 30 days), with and without an anomaly of 0.3 m/s/axis on day 100;
5. distance: monthly DSN without ΔDOR, ± "requirements" CMB, from 5 to 300 AU.

Usage (from the repository root): python studies/deep_space_study.py   (~10 min; output in results/deep_space_study.md)
"""
from __future__ import annotations

import csv
import os
import sys
import time
from multiprocessing import Pool

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from cmbsim.deep import CMB_LEVELS, DeepConfig, calibration_case, deep_metrics, run_deep   # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "results")
SEEDS = tuple(range(1, 7))
KEYS = [("r error plane of sky [km]", "r sky [km]"), ("1σ r plane of sky [km]", "1σ r sky [km]"),
        ("v error line of sight [m/s]", "v LOS [m/s]"), ("v error plane of sky [m/s]", "v sky [m/s]"),
        ("1σ v plane of sky [m/s]", "1σ v sky [m/s]")]
AUTO = dict(dsn_pass_days=7.0, dsn_until_day=30.0)

GROUPS = {
    "2. DSN alone at 100 AU (1 year)": [
        ("Weekly DSN (8 h)", dict(dsn_pass_days=7.0)),
        ("Monthly DSN", dict(dsn_pass_days=30.0)),
        ("Quarterly DSN", dict(dsn_pass_days=91.0)),
        ("Weekly DSN + ΔDOR 5 nrad", dict(dsn_pass_days=7.0, dsn_ddor_nrad=5.0)),
        ("Monthly DSN + ΔDOR 5 nrad", dict(dsn_pass_days=30.0, dsn_ddor_nrad=5.0)),
    ],
    "3. Monthly DSN + CMB": [
        ("Monthly DSN", dict(dsn_pass_days=30.0)),
        ("+ CMB, realistic", dict(dsn_pass_days=30.0, cmb_on=True, cmb_level="realistic")),
        ("+ CMB, requirements", dict(dsn_pass_days=30.0, cmb_on=True, cmb_level="requirements")),
        ("+ CMB, ideal", dict(dsn_pass_days=30.0, cmb_on=True, cmb_level="ideal")),
    ],
    "4a. Autonomous after day 30, no anomaly": [
        ("Dynamics only", dict(AUTO)),
        ("CMB, realistic", dict(AUTO, cmb_on=True, cmb_level="realistic")),
        ("CMB, requirements", dict(AUTO, cmb_on=True, cmb_level="requirements")),
        ("Compact XNAV (Ely)", dict(AUTO, xnav_on=True)),
        ("XNAV + CMB, requirements", dict(AUTO, xnav_on=True, cmb_on=True, cmb_level="requirements")),
    ],
    "4b. Autonomous after day 30, anomaly of 0.3 m/s/axis on day 100": [
        ("Dynamics only", dict(AUTO, anomaly_days=(100.0,))),
        ("IMU", dict(AUTO, anomaly_days=(100.0,), imu_on=True)),
        ("CMB, realistic", dict(AUTO, anomaly_days=(100.0,), cmb_on=True, cmb_level="realistic")),
        ("CMB, requirements", dict(AUTO, anomaly_days=(100.0,), cmb_on=True, cmb_level="requirements")),
        ("CMB, ideal", dict(AUTO, anomaly_days=(100.0,), cmb_on=True, cmb_level="ideal")),
        ("Compact XNAV (Ely)", dict(AUTO, anomaly_days=(100.0,), xnav_on=True)),
    ],
    "5. Distance: monthly DSN without ΔDOR, ± CMB, requirements": [
        (f"{r:g} AU{' + CMB' if c else ''}", dict(r0_au=r, dsn_pass_days=30.0, cmb_on=c, cmb_level="requirements"))
        for r in (5.0, 30.0, 100.0, 300.0) for c in (False, True)
    ],
}


def one(args):
    kw, s = args
    return deep_metrics(run_deep(DeepConfig(seed=s, **kw)))


def rms(x):
    return float(np.sqrt(np.mean(np.square(x))))


def main():
    t0 = time.time()
    L = ["# 100 AU mission (use case 3) — results", "",
         f"Generated by `studies/deep_space_study.py` on {time.strftime('%Y-%m-%d %H:%M')} with `cmbsim/deep.py`. RMS over "
         f"{len(SEEDS)} seeds, at the end of 1 year. Components: along the Earth→probe line of sight (LOS, what Doppler "
         "measures) and in the plane of the sky.", "",
         "## 1. Calibration of the abstract CMB model", "",
         "60-day gap at 1.5 AU with an anomaly of 0.3 m/s/axis, as in the full simulator (12 seeds). "
         "Velocity error at the end of the gap; ratio relative to the dynamics-only case.", "",
         "| Level | σ per day [m/s] | Bias [m/s] (τ [d]) | v error [m/s] | Ratio | Target (full simulator) |",
         "|---|---|---|---|---|---|"]
    target = {None: "1", "realistic": "≈ 1.0 (family D, all systematics)",
              "requirements": "0.30 (NET 0.3, chopper, 0.1″, 1 ppm)", "ideal": "0.38 (NET 1, no systematics)"}
    base = None
    for lvl in (None, "realistic", "requirements", "ideal"):
        v = rms([calibration_case(lvl, seed=s)[0] for s in range(1, 13)])
        base = v if lvl is None else base
        p = CMB_LEVELS.get(lvl, ("—", "—", "—"))
        L.append(f"| {lvl or 'dynamics only'} | {p[0]} | {p[1]} ({p[2]}) | {v:.3g} | {v / base:.2f} | {target[lvl]} |")
    L.append("")
    rows = []
    with Pool(os.cpu_count() or 2) as pool:
        for g, cases in GROUPS.items():
            L += [f"## {g}", "", "| Case | " + " | ".join(k[1] for k in KEYS) + " |", "|---|" + "---|" * len(KEYS)]
            for name, kw in cases:
                ms = pool.map(one, [(kw, s) for s in SEEDS])
                L.append(f"| {name} | " + " | ".join(f"{rms([m[k[0]] for m in ms]):.3g}" for k in KEYS) + " |")
                rows.append(dict(group=g.split(".")[0], case=name, **{k[0]: rms([m[k[0]] for m in ms]) for k in KEYS}))
            L.append("")
            print(g, f"{time.time() - t0:.0f} s", flush=True)
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, "deep_space_study.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    with open(os.path.join(OUT, "deep_space_study.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["group", "case"] + [k[0] for k in KEYS])
        w.writeheader()
        w.writerows(rows)
    print("\n".join(L))


if __name__ == "__main__":
    main()
