"""Floor budget: how the 60-day-gap velocity error grows from the analytic photon-noise floor to the simulated
photon-limit instrument, adding one effect at a time (Fig. 7 of the article).

Steps (all in the 60-day gap case at 1.5 AU with a 0.3 m/s per-axis anomaly, RMS over 6 seeds):
  A. analytic photon floor (reduced model of cmbsim/deep.py, level 'limit': 17 mm/s per day, 2 mm/s bias);
  B. four-beam geometry (reduced model, white noise of the simulated instrument: 0.10 m/s per 2-h window
     = 29 mm/s per day, no bias);
  then the full simulator with the photon-limit instrument of studies/ratio_study.py (total-power ratio receiver,
  tilted spin axis, chopper, effective NET 0.026 µK√s), switching effects on cumulatively:
  C. white noise only (statistical sky, no zodiacal, no kinematic terms, no linearization, no gain/load/attitude errors);
  D. + real sky (maps, kinematic aberration, linearized temperature);
  E. + zodiacal emission (10% model error, scale estimated);
  F. + gain calibration and drift (10 ppm each);
  G. + reference-load drift (3 nK);
  H. + attitude (1 mas alignment drift, mas-class reference) = the photon-limit level of Table VI.

Usage (from the repository root): python studies/floor_budget_study.py [--nproc N]   (~20 min on 2 cores)
Outputs: results/floor_budget_study.csv and .md
"""
from __future__ import annotations

import argparse
import csv
import os
import sys
import time
from multiprocessing import Pool

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.dirname(__file__))
import provenance                                                    # noqa: E402
import gap_study as EL                                               # noqa: E402
import ratio_study as R                                              # noqa: E402
from cmbsim.deep import calibration_case                             # noqa: E402

CSV = os.path.join(EL.OUT, "floor_budget_study.csv")
MD = os.path.join(EL.OUT, "floor_budget_study.md")
SEEDS = R.SEEDS
LIM = R.LEVELS["limit"][1]
OFF = dict(att_on=False, sky_real=False, zodi_on=False, kinematic=False, temp_linearized=False,
           gain_cal_ppm=0.0, gain_drift_ppm=0.0, load_drift_nK=0.0)
STEPS = [
    ("A", "Analytic photon floor (reduced model)", ("deep", dict(level="limit"))),
    ("B", "+ four-beam geometry (reduced model)", ("deep", dict(level="custom", cmb_sig_day_mps=0.029,
                                                                 cmb_bias_mps=0.0))),
    ("C", "Full simulator, white noise only", ("full", dict(OFF))),
    ("D", "+ real sky", ("full", dict(OFF, sky_real=True, kinematic=True, temp_linearized=True))),
    ("E", "+ zodiacal (scale estimated)", ("full", dict(OFF, sky_real=True, kinematic=True, temp_linearized=True,
                                                         zodi_on=True))),
    ("F", "+ gain (10 ppm calibration and drift)", ("full", dict(OFF, sky_real=True, kinematic=True,
                                                                  temp_linearized=True, zodi_on=True,
                                                                  gain_cal_ppm=10.0, gain_drift_ppm=10.0))),
    ("G", "+ reference load (3 nK)", ("full", dict(OFF, sky_real=True, kinematic=True, temp_linearized=True,
                                                    zodi_on=True, gain_cal_ppm=10.0, gain_drift_ppm=10.0,
                                                    load_drift_nK=3.0))),
    ("H", "+ attitude (1 mas drift) = photon-limit level", ("full", {})),
]
FIELDS = ["step", "seed", "ev_end", "sv_end", "within3"]


def one(job):
    step, seed = job
    kind, kw = dict((s[0], s[2]) for s in STEPS)[step]
    if kind == "deep":
        kw = dict(kw)
        lvl = kw.pop("level")
        ev, _ = calibration_case(lvl, seed=seed, **kw)
        return dict(step=step, seed=seed, ev_end=round(float(ev), 6), sv_end="", within3="")
    r = EL.one(dict(group="budget", case="B", gap_d=R.GAP, anomaly=True, seed=seed, net_eff=R.NET_LIM,
                    over={**LIM, **kw}))
    return dict(step=step, seed=seed, ev_end=r["ev_end"], sv_end=r["sv_end"], within3=r["within3"])


def rms(x):
    return float(np.sqrt(np.mean(np.square([float(v) for v in x]))))


def summarize(rows):
    L = ["# Floor budget of the photon-limit CMB velocimeter — results", "",
         f"Generated by `studies/floor_budget_study.py` on {time.strftime('%Y-%m-%d %H:%M')}. 60-day gap at 1.5 AU "
         f"with an anomaly of {EL.ANOM_DV} m/s per axis; RMS over {len(SEEDS)} seeds (steps A and B use "
         "the reduced model with the same seeds). Effects are added cumulatively.", "",
         "| Step | Configuration | v error [m/s] | Filter 1σ [m/s] | % within ±3σ |", "|---|---|---|---|---|"]
    for k, name, _ in STEPS:
        s_ = [r for r in rows if r["step"] == k]
        if not s_:
            continue
        sv = rms([r["sv_end"] for r in s_]) if s_[0]["sv_end"] != "" else float("nan")
        d3 = np.mean([float(r["within3"]) for r in s_]) if s_[0]["within3"] != "" else float("nan")
        L.append(f"| {k} | {name} | {rms([r['ev_end'] for r in s_]):.3g} | {sv:.2g} | {d3:.0f} |")
    with open(MD, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--nproc", type=int, default=os.cpu_count() or 2, help="number of worker processes")
    ap.add_argument("--summary", action="store_true", help="only rebuild the table from the CSV")
    ap.add_argument("--resume-anyway", action="store_true", help="resume even if the CSV was written by other code")
    a = ap.parse_args()
    rows = list(csv.DictReader(open(CSV))) if os.path.exists(CSV) else []
    if not a.summary:
        mixed = provenance.check_resume(CSV, a.resume_anyway)
        done = {(r["step"], int(r["seed"])) for r in rows}
        todo = [(k, s) for k, _, _ in STEPS for s in SEEDS if (k, s) not in done]
        new = not os.path.exists(CSV)
        with open(CSV, "a", newline="") as fh, Pool(a.nproc) as pool:
            w = csv.DictWriter(fh, fieldnames=FIELDS)
            if new:
                w.writeheader()
            for row in pool.imap_unordered(one, todo):
                w.writerow(row)
                fh.flush()
                rows.append({k: str(v) for k, v in row.items()})
                print(row, flush=True)
    if not a.summary:
        provenance.stamp(CSV, mixed)
    summarize(rows)


if __name__ == "__main__":
    main()
