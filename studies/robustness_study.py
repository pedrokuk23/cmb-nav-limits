"""Robustness checks of the photon-limit level in the 60-day gap case (full simulator).

1. Reference-load requirement at the photon-limit level: load drift swept from 3 nK to 3 µK with the photon-limit
   instrument (NET 0.026, 1 mas, ratio receiver), complementing the sweep at NET 0.083 of studies/ratio_study.py.
2. Composition of the solar and spacecraft velocities: Galilean sum in truth and filter (the default used in the
   article), relativistic composition in both, and relativistic truth with a Galilean on-board model (the error
   made by ignoring the effect).

Usage (from the repository root): python studies/robustness_study.py [--nproc N]   (~1.5 h on 2 cores)
Outputs: results/robustness_study.{csv,md}
"""
from __future__ import annotations

import argparse
import csv
import os
import sys
import time
from multiprocessing import Pool

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.dirname(__file__))
import provenance                                                    # noqa: E402
import gap_study as EL                                               # noqa: E402
import ratio_study as R                                              # noqa: E402
from cmbsim import physics as ph                                     # noqa: E402
from cmbsim.simulator import Config, run                             # noqa: E402

CSV = os.path.join(EL.OUT, "robustness_study.csv")
MD = os.path.join(EL.OUT, "robustness_study.md")
SEEDS = R.SEEDS
LIM = R.LEVELS["limit"][1]
LOADS = (3.0, 30.0, 300.0, 1000.0, 3000.0)
COMPOSITION = {"galilean": (False, False), "relativistic": (True, True), "rel_truth_gal_filter": (True, False)}
FIELDS = ["group", "case", "param", "seed", "ev_end", "sv_end", "within3"]


def jobs():
    out = []
    for s in SEEDS:
        for ld in LOADS:
            out.append(("load_limit", "total", ld, s))
        for k in COMPOSITION:
            out.append(("composition", k, 0, s))
    return out


def one(job):
    group, case, param, seed = job
    over = dict(LIM)
    if group == "load_limit":
        over["load_drift_nK"] = float(param)
    else:
        over["rel_truth"], over["rel_filter"] = COMPOSITION[case]
    a, b = EL.GAP_START, EL.GAP_START + R.GAP
    kw = {**EL.BASE, **over, "seed": seed, "dsn_gaps": ((a, b),), "end_day": b + 2.0,
          "anomaly_days": (a + 2.0,), "anomaly_dv_mps": EL.ANOM_DV}
    r = run(Config(**kw))
    d = r.t / ph.DAY
    m = (d >= a) & (d <= b)
    e = (r.x_est[m, 3:6] - r.x_true[m, 3:]) * 1e3
    s = np.sqrt(r.P_diag[m, 3:6]) * 1e3
    return dict(group=group, case=case, param=param, seed=seed, ev_end=round(float(np.linalg.norm(e[-1])), 5),
                sv_end=round(float(np.linalg.norm(s[-1])), 5),
                within3=round(float(np.mean(np.abs(e / s) <= 3) * 100), 1))


def rms(x):
    return float(np.sqrt(np.mean(np.square([float(v) for v in x]))))


def summarize(rows):
    L = ["# Robustness of the photon-limit level (60-day gap) — results", "",
         f"Generated by `studies/robustness_study.py` on {time.strftime('%Y-%m-%d %H:%M')}. RMS over {len(SEEDS)} "
         "seeds of the velocity error at the end of the gap.", "",
         "## 1. Reference-load drift at the photon-limit level (NET 0.026, 1 mas, ratio receiver)", "",
         "| Load drift [nK] | v error [m/s] | Filter 1σ [m/s] | Within ±3σ [%] |", "|---|---|---|---|"]
    for ld in LOADS:
        s_ = [r for r in rows if r["group"] == "load_limit" and float(r["param"]) == ld]
        if s_:
            L.append(f"| {ld:g} | {rms([r['ev_end'] for r in s_]):.3g} | {rms([r['sv_end'] for r in s_]):.3g} | "
                     f"{np.mean([float(r['within3']) for r in s_]):.0f} |")
    L += ["", "## 2. Composition of the solar and spacecraft velocities", "",
          "| Truth / on-board model | v error [m/s] | Filter 1σ [m/s] | Within ±3σ [%] |", "|---|---|---|---|"]
    names = {"galilean": "Galilean / Galilean (article)", "relativistic": "relativistic / relativistic",
             "rel_truth_gal_filter": "relativistic / Galilean"}
    for k in COMPOSITION:
        s_ = [r for r in rows if r["group"] == "composition" and r["case"] == k]
        if s_:
            L.append(f"| {names[k]} | {rms([r['ev_end'] for r in s_]):.3g} | {rms([r['sv_end'] for r in s_]):.3g} | "
                     f"{np.mean([float(r['within3']) for r in s_]):.0f} |")
    with open(MD, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--nproc", type=int, default=os.cpu_count() or 2, help="number of worker processes")
    ap.add_argument("--summary", action="store_true", help="only rebuild the table from the CSV")
    ap.add_argument("--resume-anyway", action="store_true", help="resume even if the CSV was written by other code")
    a = ap.parse_args()
    rows = list(csv.DictReader(open(CSV))) if os.path.exists(CSV) else []
    if a.summary:
        summarize(rows)
        return
    mixed = provenance.check_resume(CSV, a.resume_anyway)
    done = {(r["group"], r["case"], f"{float(r['param']):g}", int(r["seed"])) for r in rows}
    todo = [j for j in jobs() if (j[0], j[1], f"{float(j[2]):g}", j[3]) not in done]
    new = not os.path.exists(CSV)
    with open(CSV, "a", newline="") as fh, Pool(a.nproc) as pool:
        w = csv.DictWriter(fh, fieldnames=FIELDS)
        if new:
            w.writeheader()
        for row in pool.imap_unordered(one, todo):
            w.writerow(row)
            fh.flush()
            rows.append({k: str(v) for k, v in row.items()})
            print(row, flush=True)
    provenance.stamp(CSV, mixed)
    summarize(rows)


if __name__ == "__main__":
    main()
