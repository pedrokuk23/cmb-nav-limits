"""100 AU mission with the "metrology" and "limit" levels calibrated against the full simulator (ratio_study).

Repeats groups 3 and 4 of studies/deep_space_study.py with the `metrology_sim` and `limit_sim` levels of
cmbsim/deep.py, alongside the analytic levels (`metrology`, `limit`), to measure how much the conclusion of use
case 3 changes.

Usage (from the repository root): python studies/deep_space_calibrated_study.py
(~5 min; outputs results/deep_space_calibrated_study.md and .csv, used by figures/make_figures.py)
"""
from __future__ import annotations

import csv
import os
import sys
import time
from multiprocessing import Pool

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.dirname(__file__))
from cmbsim.deep import CMB_LEVELS, calibration_case                       # noqa: E402
import deep_space_study as E                                                     # noqa: E402

LEVELS = ("realistic", "requirements_sim", "ratio_sim", "metrology", "metrology_sim", "limit", "limit_sim")
AN = dict(E.AUTO, anomaly_days=(100.0,))
GROUPS = {
    "3. Monthly DSN + CMB": [("Monthly DSN", dict(dsn_pass_days=30.0))]
    + [(f"+ CMB {lv}", dict(dsn_pass_days=30.0, cmb_on=True, cmb_level=lv)) for lv in LEVELS],
    "4a. Autonomous after day 30, no anomaly": [("Dynamics only", dict(E.AUTO)), ("XNAV", dict(E.AUTO, xnav_on=True))]
    + [(f"CMB {lv}", dict(E.AUTO, cmb_on=True, cmb_level=lv)) for lv in LEVELS]
    + [(f"XNAV + CMB {lv}", dict(E.AUTO, xnav_on=True, cmb_on=True, cmb_level=lv)) for lv in LEVELS],
    "4b. Autonomous after day 30, anomaly of 0.3 m/s/axis on day 100": [
        ("Dynamics only", dict(AN)), ("IMU", dict(AN, imu_on=True)), ("XNAV", dict(AN, xnav_on=True))]
    + [(f"CMB {lv}", dict(AN, cmb_on=True, cmb_level=lv)) for lv in LEVELS],
}


def main():
    t0 = time.time()
    L = ["# 100 AU mission with levels calibrated in the full simulator — results", "",
         f"Generated by `studies/deep_space_calibrated_study.py` on {time.strftime('%Y-%m-%d %H:%M')}. RMS over "
         f"{len(E.SEEDS)} seeds at the end of 1 year; `*_sim` = levels calibrated against studies/ratio_study.py.", "",
         "## Calibration (60 d gap at 1.5 AU, anomaly; 12 seeds)", "",
         "| Level | σ per day [m/s] | Bias [m/s] | v error [m/s] |", "|---|---|---|---|"]
    for lv in LEVELS:
        v = E.rms([calibration_case(lv, seed=s)[0] for s in range(1, 13)])
        p = CMB_LEVELS[lv]
        L.append(f"| {lv} | {p[0]} | {p[1]} | {v:.3g} |")
    L.append("")
    rows = [dict(group="calibration", case=lv, **{"v error total [m/s]": E.rms([calibration_case(lv, seed=s)[0]
                                                                                for s in range(1, 13)])})
            for lv in LEVELS]
    with Pool(os.cpu_count() or 2) as pool:
        for g, cases in GROUPS.items():
            L += [f"## {g}", "", "| Case | " + " | ".join(k[1] for k in E.KEYS) + " |", "|---|" + "---|" * len(E.KEYS)]
            for name, kw in cases:
                ms = pool.map(E.one, [(kw, s) for s in E.SEEDS])
                L.append(f"| {name} | " + " | ".join(f"{E.rms([m[k[0]] for m in ms]):.3g}" for k in E.KEYS) + " |")
                rows.append(dict(group=g.split(".")[0], case=name, **{k[0]: E.rms([m[k[0]] for m in ms]) for k in E.KEYS}))
            L.append("")
            print(g, f"{time.time() - t0:.0f} s", flush=True)
    with open(os.path.join(E.OUT, "deep_space_calibrated_study.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    fields = ["group", "case", "v error total [m/s]"] + [k[0] for k in E.KEYS]
    with open(os.path.join(E.OUT, "deep_space_calibrated_study.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fields)
        w.writeheader()
        w.writerows({f: r.get(f, "") for f in fields} for r in rows)
    print("\n".join(L))


if __name__ == "__main__":
    main()
