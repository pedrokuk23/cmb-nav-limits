"""Reproducible calibration of the abstract CMB velocimeter of cmbsim/deep.py against the full simulator.

The reduced model represents a CMB level by three numbers: white noise per day σ, a Gauss-Markov bias b and its
correlation time τ (CMB_LEVELS in cmbsim/deep.py). For each `*_sim` level this script keeps the shape of the error
model fixed (the ratio b/σ and τ written in CMB_LEVELS, which are modeling choices) and solves for the single scale
factor s such that the reduced model, on the common calibration case (60-day gap at 1.5 AU with a 0.3 m/s per-axis
anomaly, 12 seeds, `deep.calibration_case`), reproduces the velocity error of the full simulator on the same case
(RMS over 6 seeds, UKF rows of results/consistency_study.csv).

It reports the fitted (σ, b) next to the values stored in CMB_LEVELS. It does not modify CMB_LEVELS: the 100 AU
results use the stored values, and this script shows that they agree with the fit.

Note: the calibration fixes the reduced model at 1.5 AU. Using it at 100 AU assumes that the instrument error
model does not get worse with distance; the zodiacal foreground, the only distance-dependent term in the full
simulator, decreases outward.

Usage (from the repository root): python studies/deep_space_calibration_fit.py   (~3 min)
Outputs: results/deep_space_calibration_fit.{csv,md}
"""
from __future__ import annotations

import csv
import os
import sys
import time

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from cmbsim.deep import CMB_LEVELS, calibration_case                       # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "results")
FULL = os.path.join(OUT, "consistency_study.csv")
SEEDS = range(1, 13)
LEVELS = {"requirements_sim": "req", "ratio_sim": "ratio", "metrology_sim": "metro", "limit_sim": "limit"}


def rms(x):
    return float(np.sqrt(np.mean(np.square(x))))


def reduced_error(sig, bias, tau):
    return rms([calibration_case("custom", seed=s, cmb_sig_day_mps=sig, cmb_bias_mps=bias,
                                 cmb_bias_tau_d=tau)[0] for s in SEEDS])


def fit_scale(sig0, bias0, tau, target, lo=0.1, hi=10.0, tol=1e-3):
    """Bisection on log(s); the gap error increases monotonically with the noise scale."""
    f = lambda s: reduced_error(s * sig0, s * bias0, tau) - target            # noqa: E731
    flo, fhi = f(lo), f(hi)
    if flo > 0 or fhi < 0:
        raise RuntimeError(f"target {target} outside the range reachable with s in [{lo}, {hi}]")
    for _ in range(40):
        mid = np.sqrt(lo * hi)
        if f(mid) > 0:
            hi = mid
        else:
            lo = mid
        if hi / lo - 1 < tol:
            break
    return np.sqrt(lo * hi)


def main():
    t0 = time.time()
    full = list(csv.DictReader(open(FULL)))
    rows = []
    for lv, case in LEVELS.items():
        target = rms([float(r["ev_end"]) for r in full if r["case"] == case and r["filter"] == "ukf"])
        sig0, bias0, tau = CMB_LEVELS[lv]
        s = fit_scale(sig0, bias0, tau, target)
        stored = reduced_error(sig0, bias0, tau)
        rows.append(dict(level=lv, full_sim_target=round(target, 5), stored_sigma=sig0, stored_bias=bias0, tau_d=tau,
                         stored_error=round(stored, 5), fitted_sigma=round(s * sig0, 4), fitted_bias=round(s * bias0, 4),
                         scale_fitted_over_stored=round(s, 3)))
        print(rows[-1], f"{time.time() - t0:.0f} s", flush=True)
    with open(os.path.join(OUT, "deep_space_calibration_fit.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    L = ["# Calibration of the reduced-model CMB levels against the full simulator — results", "",
         f"Generated by `studies/deep_space_calibration_fit.py` on {time.strftime('%Y-%m-%d %H:%M')}. Target: full "
         "simulator, 60-day gap at 1.5 AU with a 0.3 m/s per-axis anomaly, RMS over 6 seeds (UKF rows of "
         "`results/consistency_study.csv`). Reduced model on the same case, 12 seeds. The ratio b/σ and τ are "
         "kept as stored; only the overall scale is fitted.", "",
         "| Level | Full-simulator target [m/s] | Stored σ; b [m/s] | Reduced model with stored values [m/s] | "
         "Fitted σ; b [m/s] | Fitted / stored |", "|---|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['level']} | {r['full_sim_target']:.3g} | {r['stored_sigma']}; {r['stored_bias']} | "
                 f"{r['stored_error']:.3g} | {r['fitted_sigma']:.3g}; {r['fitted_bias']:.3g} | "
                 f"{r['scale_fitted_over_stored']:.2f} |")
    with open(os.path.join(OUT, "deep_space_calibration_fit.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
