"""Chromatic gain of the ratio receiver at the photon-limit level (60-day gap, full simulator).

A broadband detector measures band-averaged intensity. In CMB temperature units the dipole channels give D and the
monopole channel gives [I(T0) - I(T_L)] / I'(T0), which is T0/κ for a cold load, with κ = d ln I / d ln T at T0
averaged over the band. The dipole-to-monopole ratio is therefore κ D / T0: it is free of the achromatic gain
(detector responsivity, electronics) but proportional to κ, which depends on the shape of the spectral response.
A drift of κ scales the dipole channels and leaves the monopole channel unchanged. That is the gain model of the
differential receiver, so the study runs the photon-limit level with the differential receiver and a gain drift
equal to the κ drift (Gauss-Markov, same correlation time; the filter estimates it).

The script also tabulates κ, its sensitivity to the band center, and the physical load-temperature stability that
corresponds to a reference-brightness stability δT_L / T0 = 1.1e-8 (30 nK in CMB temperature units).

Usage (from the repository root): python studies/chromatic_study.py [--nproc N]   (~15 min on 2 cores)
Outputs: results/chromatic_study.{csv,md}
"""
from __future__ import annotations

import argparse
import csv
import os
import sys
import time
from multiprocessing import Pool

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.dirname(__file__))
import provenance                                                    # noqa: E402
import gap_study as EL                                               # noqa: E402
import ratio_study as R                                              # noqa: E402
from cmbsim import physics as ph                                     # noqa: E402
from cmbsim.simulator import Config, run                             # noqa: E402

CSV = os.path.join(EL.OUT, "chromatic_study.csv")
MD = os.path.join(EL.OUT, "chromatic_study.md")
SEEDS = R.SEEDS
LIM = R.LEVELS["limit"][1]
DRIFTS_PPM = (0.01, 0.1, 1.0)
BANDS_GHZ = (90.0, 150.0, 220.0)
LOADS_K = (1.0, 1.5, 2.0)
FIELDS = ["drift_ppm", "seed", "ev_end", "sv_end", "within3"]


def band(nu_ghz, frac=0.25, n=41):
    return nu_ghz * 1e9 * (1.0 + frac * np.linspace(-0.5, 0.5, n))


def intensity(T, nus):
    return float(np.mean(nus**3 / np.expm1(ph.H_PLANCK * nus / (ph.K_BOLTZ * T))))


def d_intensity(T, nus):
    x = ph.H_PLANCK * nus / (ph.K_BOLTZ * T)
    return float(np.mean(nus**3 * (x / T) * np.exp(x) / np.expm1(x) ** 2))


def kappa(nus, T0=ph.T0_CMB):
    return T0 * d_intensity(T0, nus) / intensity(T0, nus)


def one(job):
    drift, seed = job
    over = dict(LIM, receiver="differential", gain_drift_ppm=float(drift))
    a, b = EL.GAP_START, EL.GAP_START + R.GAP
    kw = {**EL.BASE, **over, "seed": seed, "dsn_gaps": ((a, b),), "end_day": b + 2.0,
          "anomaly_days": (a + 2.0,), "anomaly_dv_mps": EL.ANOM_DV}
    r = run(Config(**kw))
    d = r.t / ph.DAY
    m = (d >= a) & (d <= b)
    e = (r.x_est[m, 3:6] - r.x_true[m, 3:]) * 1e3
    s = np.sqrt(r.P_diag[m, 3:6]) * 1e3
    return dict(drift_ppm=drift, seed=seed, ev_end=round(float(np.linalg.norm(e[-1])), 5),
                sv_end=round(float(np.linalg.norm(s[-1])), 5),
                within3=round(float(np.mean(np.abs(e / s) <= 3) * 100), 1))


def rms(x):
    return float(np.sqrt(np.mean(np.square([float(v) for v in x]))))


def summarize(rows):
    T0 = ph.T0_CMB
    frac = 30e-9 / T0
    L = ["# Chromatic gain of the ratio receiver at the photon-limit level — results", "",
         f"Generated by `studies/chromatic_study.py` on {time.strftime('%Y-%m-%d %H:%M')}.", "",
         "## 1. Band-averaged logarithmic slope κ = d ln I / d ln T at T0 (25 % flat band)", "",
         "| Band [GHz] | κ | Change of κ for +1 % band center [%] | "
         + " | ".join(f"Load stability for δT_L/T0 = {frac:.1e}, T_L = {t:g} K" for t in LOADS_K) + " |",
         "|---|---|---|" + "---|" * len(LOADS_K)]
    for nu in BANDS_GHZ:
        nus = band(nu)
        k0, k1 = kappa(nus), kappa(nus * 1.01)
        cells = []
        for tl in LOADS_K:
            dT = frac * (intensity(T0, nus) - intensity(tl, nus)) / d_intensity(tl, nus)
            cells.append(f"{dT * 1e9:.3g} nK")
        L.append(f"| {nu:g} | {k0:.3f} | {100 * (k1 / k0 - 1):.2f} | " + " | ".join(cells) + " |")
    L += ["", "## 2. Drift of κ at the photon-limit level (60-day gap, emulated as a dipole-channel gain drift)", "",
          f"RMS over {len(SEEDS)} seeds of the velocity error at the end of the gap.", "",
          "| κ drift [ppm] | v error [m/s] | Filter 1σ [m/s] | Within ±3σ [%] |", "|---|---|---|---|"]
    for dr in DRIFTS_PPM:
        s_ = [r for r in rows if float(r["drift_ppm"]) == dr]
        if s_:
            L.append(f"| {dr:g} | {rms([r['ev_end'] for r in s_]):.3g} | {rms([r['sv_end'] for r in s_]):.3g} | "
                     f"{np.mean([float(r['within3']) for r in s_]):.0f} |")
    with open(MD, "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--nproc", type=int, default=os.cpu_count() or 2, help="number of worker processes")
    ap.add_argument("--summary", action="store_true", help="only rebuild the tables from the CSV")
    ap.add_argument("--resume-anyway", action="store_true", help="resume even if the CSV was written by other code")
    a = ap.parse_args()
    rows = list(csv.DictReader(open(CSV))) if os.path.exists(CSV) else []
    if a.summary:
        summarize(rows)
        return
    mixed = provenance.check_resume(CSV, a.resume_anyway)
    done = {(f"{float(r['drift_ppm']):g}", int(r["seed"])) for r in rows}
    todo = [(d, s) for d in DRIFTS_PPM for s in SEEDS if (f"{d:g}", s) not in done]
    new = not os.path.exists(CSV)
    with open(CSV, "a", newline="") as fh, Pool(a.nproc) as pool:
        w = csv.DictWriter(fh, fieldnames=FIELDS)
        if new:
            w.writeheader()
        for row in pool.imap_unordered(one, todo):
            w.writerow(row)
            fh.flush()
            rows.append({k: str(v) for k, v in row.items()})
            print(row, flush=True)
    provenance.stamp(CSV, mixed)
    summarize(rows)


if __name__ == "__main__":
    main()
