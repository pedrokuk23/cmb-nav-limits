"""Bootstrap intervals over the seeds for the key comparisons of the article (Section VII, statistical support).

For each case, the six per-seed errors are resampled with replacement (10 000 resamples, fixed generator seed) and
the RMS of each resample is computed; the interval is the 16th-84th percentile of those RMS values (percentile
bootstrap, 68 %). The gap case reads the per-seed rows of results/ratio_study.csv; the 100 AU cases re-run the
reduced model of cmbsim/deep.py per seed (same configurations as studies/deep_space_calibrated_study.py).

Usage (from the repository root): python studies/seed_intervals.py   (~2 min)
Outputs: results/seed_intervals.{csv,md}
"""
from __future__ import annotations

import csv
import os
import sys
import time
from multiprocessing import Pool

import numpy as np

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.dirname(__file__))
import deep_space_calibrated_study as C                                    # noqa: E402
import deep_space_study as E                                               # noqa: E402

OUT = os.path.join(os.path.dirname(__file__), "..", "results")
N_BOOT = 10_000
RNG_SEED = 2026
SKY = "v error plane of sky [m/s]"


def rms(x):
    return float(np.sqrt(np.mean(np.square(x))))


def interval(x, n=N_BOOT, seed=RNG_SEED):
    x = np.asarray(x, float)
    rng = np.random.default_rng(seed)
    boot = np.sqrt(np.mean(np.square(x[rng.integers(0, len(x), (n, len(x)))]), axis=1))
    lo, hi = np.percentile(boot, [16, 84])
    return rms(x), float(lo), float(hi)


def gap_cases():
    rows = list(csv.DictReader(open(os.path.join(OUT, "ratio_study.csv"))))
    out = []
    for case, label in (("limit", "CMB photon limit"), ("imu", "IMU"), ("xnav", "XNAV"), ("dyn", "Dynamics only")):
        x = [float(r["ev_end"]) for r in rows if r["group"] == "levels" and r["case"] == case]
        out.append(("60-day gap, 1.5 AU (velocity error, end of gap)", label, x))
    return out


def deep_cases(pool):
    sel = {"3": ["Monthly DSN", "+ CMB limit_sim"], "4b": ["IMU", "XNAV", "CMB limit_sim"]}
    names = {"3": "100 AU, monthly DSN (plane-of-sky velocity error)",
             "4b": "100 AU, autonomous after day 30, anomaly (plane-of-sky velocity error)"}
    out = []
    for g, cases in C.GROUPS.items():
        key = g.split(".")[0]
        for name, kw in cases:
            if name in sel.get(key, []):
                ms = pool.map(E.one, [(kw, s) for s in E.SEEDS])
                out.append((names[key], name, [m[SKY] for m in ms]))
    return out


def main():
    t0 = time.time()
    with Pool(os.cpu_count() or 2) as pool:
        cases = gap_cases() + deep_cases(pool)
    rows = []
    for scen, name, x in cases:
        r, lo, hi = interval(x)
        rows.append(dict(scenario=scen, case=name, n_seeds=len(x), rms=round(r, 5), lo68=round(lo, 5),
                         hi68=round(hi, 5), per_seed=" ".join(f"{v:.5g}" for v in x)))
    with open(os.path.join(OUT, "seed_intervals.csv"), "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    L = ["# Bootstrap intervals over the seeds — results", "",
         f"Generated by `studies/seed_intervals.py` on {time.strftime('%Y-%m-%d %H:%M')}. Percentile bootstrap of the "
         f"RMS over seeds, {N_BOOT} resamples, 68 % interval (16th-84th percentile).", "",
         "| Scenario | Case | Seeds | RMS [m/s] | 68 % interval [m/s] |", "|---|---|---|---|---|"]
    for r in rows:
        L.append(f"| {r['scenario']} | {r['case']} | {r['n_seeds']} | {r['rms']:.3g} | {r['lo68']:.3g}–{r['hi68']:.3g} |")
    with open(os.path.join(OUT, "seed_intervals.md"), "w") as fh:
        fh.write("\n".join(L) + "\n")
    print("\n".join(L))
    print(f"{time.time() - t0:.0f} s")


if __name__ == "__main__":
    main()
